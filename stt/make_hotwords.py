#!/usr/bin/env python3
"""
make_hotwords.py - builds stt/hotwords.txt (plain phrases the streaming STT should favour):
exposed HA entity names + our STT aliases + area names + playlist names + people/products.
Run from the repo root with config.env loaded (HA_URL, HA_TOKEN); then deploy the file to the voice host
(/opt/casa-stt/hotwords.txt) and restart casa-stt. Re-run whenever devices/playlists are renamed.
"""
import json, os, re, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # casa-voice repo root
OUT = os.path.join(ROOT, "stt", "hotwords.txt")
HA_URL = os.environ.get("HA_URL", "http://127.0.0.1:8123")
TOKEN = os.environ["HA_TOKEN"]

# Words the streaming model should favour that are not entity names: people, brands, playlists, cities you ask about.
# (My own list had our names, our playlists and the cities we ask about; put yours here.)
EXTRA = [
    "Casa", "thermostat", "soundbar", "blinds", "humidifier", "diffuser", "pendant", "overhead", "backlight",
    "monitor light", "sofa light", "desk lamp", "movie mode", "dinner mode", "bedtime", "wake up", "work mode",
    "good night", "all off", "white noise", "brown noise",
    # "<person name>", "<playlist name>", "<city>",
]
COMMON = {"light", "lights", "the", "a", "an", "of", "in", "on", "off", "sensor", "switch", "temperature", "humidity",
          "battery", "zone", "1", "2", "3", "speaker", "media", "player", "presence", "illuminance"}


def get(path):
    req = urllib.request.Request(HA_URL + path, headers={"Authorization": f"Bearer {TOKEN}"})
    return json.load(urllib.request.urlopen(req, timeout=10))


phrases = []
states = get("/api/states")
for s in states:
    e = s["entity_id"]
    if e.split(".")[0] not in ("light", "switch", "fan", "cover", "humidifier", "climate", "media_player", "scene", "script", "input_select", "timer"):
        continue
    name = s["attributes"].get("friendly_name")
    if name and s["state"] != "unavailable":
        phrases.append(name)
for f in ("aliases.json", "area_aliases.json"):
    p = os.path.join(ROOT, "ai-eval", f)
    if os.path.exists(p):
        for v in json.load(open(p)).values():
            phrases += v
phrases += EXTRA

seen, out = set(), []
for p in phrases:
    p = re.sub(r"\s+", " ", p.strip())
    p = re.sub(r"[^\w' áéíóúñÁÉÍÓÚÑ-]", "", p)
    key = p.lower()
    if not key or key in seen or key in COMMON or len(key) < 3:
        continue
    seen.add(key)
    out.append(p)
    # single-word names inside a phrase (e.g. "Jon's light" -> "Jon") are covered by EXTRA
with open(OUT, "w", encoding="utf-8") as f:
    f.write("# casa-stt hotwords - generated by stt/make_hotwords.py; one phrase per line, optional ' :score'\n")
    f.write("\n".join(out) + "\n")
print(f"{len(out)} phrases -> {OUT}")
